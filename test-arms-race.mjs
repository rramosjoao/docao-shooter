import assert from 'node:assert/strict';
import { Game } from './server/src/game.js';
import { ARMS_STAGES, ARMS_LAST, armsRaceKill, equipArmsRace } from './shared/arms-race.js';
import { KNIFE, GOLD_KNIFE } from './shared/rules.js';
const g = new Game({mode:'arms',map:'arena',max:4,fillBots:false,time:1}, {send(){},broadcast(){},startLoop(){},stopLoop(){}});
const a=g.join({name:'A'}).ent,b=g.join({name:'B'}).ent,c=g.join({name:'C'}).ent;
g.startMatch('arena'); a.team=c.team=0; b.team=1;
assert.equal(g.timeLimit,Infinity);
assert.equal(a.weapon,ARMS_STAGES[0].weapon);
const kill=(weapon=a.weapon)=>{g.spawn(b);g.kill(b,a,weapon,false);};
kill(); assert.deepEqual([a.armsStage,a.armsKills],[0,1]);
kill(); assert.deepEqual([a.armsStage,a.armsKills],[1,0]);
assert.equal(a.weapon,ARMS_STAGES[1].weapon);
const before=[a.armsStage,a.armsKills];
armsRaceKill(a,c,a.weapon); armsRaceKill(a,a,a.weapon); armsRaceKill(null,a,a.weapon);
assert.deepEqual([a.armsStage,a.armsKills],before);
b.armsStage=3;b.armsKills=1;kill(KNIFE);
assert.deepEqual([a.armsStage,a.armsKills,b.armsStage,b.armsKills],[2,0,2,0]);
g.spawn(b);assert.equal(b.weapon,ARMS_STAGES[2].weapon);
g.kill(b,a,a.weapon,false); const deaths=b.deaths; g.kill(b,a,a.weapon,false); assert.equal(b.deaths,deaths);
a.armsStage=ARMS_LAST;g.equipArms(a);assert.deepEqual(a.slots,[GOLD_KNIFE]);
g.onEvent(a,['pr',0,4,KNIFE]);g.onEvent(a,['px',0,4,KNIFE]);assert.deepEqual(a.slots,[GOLD_KNIFE]);
const token=a.token;g.leave(a.id);const reconnect=g.join({name:'A',token}).ent;assert.equal(reconnect,a);assert.equal(a.armsStage,ARMS_LAST);
a.alive=true;kill(GOLD_KNIFE);assert.equal(g.pendingEnd,true);assert.equal(g.endMsg().winner,a.id);assert.equal(g.endMsg().winTeam,0);
g.endMatch();g.startMatch('arena');assert.deepEqual([a.armsStage,a.armsKills],[0,0]);
const p={armsStage:ARMS_LAST,armsKills:0};equipArmsRace(p);assert(!p.slots.includes(KNIFE));
console.log('OK: sequência, 2 abates, negativos, roubo, persistência, reconexão, bloqueio de classes, vitória individual/time e nova partida.');
